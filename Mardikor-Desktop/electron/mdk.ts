export function renameMdkEntry(
  file: string,
  id: string,
  filename: string,
  revision?: string,
) {
  const doc = load(file, revision),
    control = contents(doc),
    entry =
      control.entries.find((e) => e.id === id) ?? manuscriptById(control, id);
  if (!entry) throw new Error(t("目录项不存在。"));
  assertEditable(doc);
  if (entry.kind === "group") {
    Object.assign(entry, withEntryTitle(entry, filename));
    putContents(doc, control);
    commit(file, doc);
    return project(doc);
  }
  const name = uniqueName(
    doc,
    path.posix.dirname(entry.path),
    filename.endsWith(".md") ? filename : `${filename}.md`,
    entry.path,
  );
  const beforeIssues = new Set(
    referenceIssues(doc)
      .filter((i) => i.code === "E_RESOURCE_MISSING")
      .map((i) => i.path + "|" + i.message),
  );
  if (name !== entry.path) {
    const previous = entry.path;
    if (!doc.zip.getEntry(previous))
      throw new Error(t("工程中没有文件：{0}", previous));
    rewriteMdkPaths(doc, (candidate) =>
      candidate === previous ? name : undefined,
    );
    for (const item of control.entries)
      if (item.path === previous) item.path = name;
    if (!control.entries.some((item) => item.documentId === entry.documentId)) {
      const raw = coreTable(doc, "contents.toml");
      for (const document of raw.documents as Table[])
        if (document.id === entry.documentId) document.path = name;
      put(doc, "contents.toml", stringify(raw));
    }
  }
  putContents(doc, control);
  if (
    referenceIssues(doc).some(
      (i) =>
        i.code === "E_RESOURCE_MISSING" &&
        !beforeIssues.has(i.path + "|" + i.message),
    )
  )
    throw new Error(
      t(
        "重命名将破坏已知引用；无法无损同步引用，已保留原路径。请先在源码中调整依赖。",
      ),
    );
  assertEditable(doc);
  commit(file, doc);
  return project(doc);
}
