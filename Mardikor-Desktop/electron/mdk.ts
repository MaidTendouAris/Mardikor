function projectFiles(doc: Document): MdkProject["files"] {
  return doc.zip.getEntries().map((e) => ({
    path: e.entryName.replace(/\/$/, ""),
    bytes: e.header.size,
    is_text: !e.isDirectory && e.header.size <= BUFFERED_ENTRY_LIMIT &&
      !e.entryName.startsWith("resources/") && isTextData(e.header.size > 65536 ? e.prefix(65536) : e.getData(), e.entryName),
    ...(e.entryName === CONTENTS_MARKDOWN_PATH &&
    isGeneratedContents(e.prefix())
      ? { readonly: true }
      : {}),
    kind: e.isDirectory
      ? "directory"
      : controlFiles.includes(e.entryName)
        ? "control"
        : e.entryName.startsWith("markdown/")
          ? "markdown"
          : e.entryName.startsWith("resources/")
            ? "resource"
            : e.entryName.startsWith("meta/")
              ? "meta"
              : "other",
  }));
}

function isTextData(data: Buffer, name = "") {
  if (
    /\.(pdf|zip|mdk|epub|png|jpe?g|webp|gif|bmp|mp[34]|aac|m4a|ogg|flac|wav|webm|ttf|otf|woff2?)$/i.test(
      name,
    )
  )
    return false;
  const media = detectMediaType(data);
  if (media && media !== "image/svg+xml") return false;
  try {
    const value = text(data);
    for (let i = 0; i < value.length; i++)
      if (value.charCodeAt(i) < 32 && !"\r\n\t".includes(value[i]))
        return false;
    return true;
  } catch {
    return false;
  }
}

function put(doc: Document, name: string, value: string | Buffer) {
  validatePath(name);
  if (!doc.zip.getEntry(name) && name !== name.normalize("NFC"))
    throw new Error(
      t("新建包内路径必须使用 Unicode NFC：{0}", displayArchivePath(name)),
    );
  doc.zip.add(
    name,
    typeof value === "string" ? Buffer.from(value, "utf8") : value,
  );
}

