function referenceIssues(doc: Document): ValidationIssue[] {
  const issues: ValidationIssue[] = [],
    used = new Set<string>();
  const files = new Set(
    doc.zip
      .getEntries()
      .filter((e) => !e.isDirectory)
      .map((e) => e.entryName),
  );
  const directories = new Set<string>();
  for (const entry of doc.zip.getEntries()) {
    const parts = entry.entryName.split("/");
    for (let depth = 1; depth < parts.length; depth++) directories.add(parts.slice(0, depth).join("/"));
  }
  const check = (source: string, url: string, media = false) => {
    const target = resolveReference(source, url, media);
    if (target.kind === "unsafe") {
      issues.push({
        severity: "error",
        code: "E_REFERENCE_UNSAFE",
        path: source,
        message: target.message,
      });
      return;
    }
    if (target.kind === "external") {
      if (target.media)
        issues.push({
          severity: "error",
          code: "E_EXTERNAL_MEDIA",
          path: source,
          message: t("portable 交付需要包内媒体：") + url,
        });
      return;
    }
    used.add(target.path);
    if (target.path.startsWith("state/")) {
      issues.push({
        severity: "error",
        code: "E_REFERENCE_UNSAFE",
        path: source,
        message: t("正文不能引用 state/ 中的可重建数据。"),
      });
      return;
    }
    if (!files.has(target.path))
      issues.push({
        severity: "error",
        code: directories.has(target.path) ? "E_REFERENCE_UNSAFE" : "E_RESOURCE_MISSING",
        path: source,
        message: directories.has(target.path) ? t("附件引用指向目录：{0}", target.path) : t("本地引用的文件不存在：") + target.path,
      });
    else {
      const hash = target.suffix.indexOf("#");
      const query = hash < 0 ? target.suffix : target.suffix.slice(0, hash);
      const fragment = hash < 0 ? "" : target.suffix.slice(hash + 1);
      if (query.length > 1)
        issues.push({
          severity: "error",
          status: "unverified",
          code: "E_REFERENCE_QUERY",
          path: source,
          message: t("未支持包内链接的查询参数：{0}", url),
        });
      if (fragment) {
        if (
          target.path.startsWith("markdown/") &&
          target.path.endsWith(".md")
        ) {
          let found = false;
          try {
            const anchor = decodeURIComponent(fragment);
            let anchors = headings.get(target.path);
            if (!anchors) {
              const tokens = markdownParser.parse(
                readText(doc, target.path),
                {},
              );
              anchors = new Set(v2HeadingAnchors(tokens).values());
              headings.set(target.path, anchors);
            }
            found = anchors.has(anchor);
          } catch {
            /* Reject invalid or unavailable fragment targets. */
          }
          if (!found)
            issues.push({
              severity: "error",
              code: "E_RESOURCE_MISSING",
              path: source,
              message: t("标题锚点不存在：{0}", url),
            });
        } else
          issues.push({
            severity: "error",
            status: "unverified",
            code: "E_REFERENCE_FRAGMENT",
            path: source,
            message: t("未支持此媒体链接的片段：{0}", url),
          });
      }
      if (media) {
        const entry = doc.zip.getEntry(target.path)!;
        const kind = detectMediaType(entry.prefix());
        if (!kind?.startsWith("image/")) {
          issues.push({ severity: "error", code: "E_MEDIA", path: source,
            message: t("图片引用指向非图像文件：{0}", target.path) });
          return;
        }
        try {
          if (entry.header.size > BUFFERED_ENTRY_LIMIT) archiveLimit(t("预览图片"), target.path, entry.header.size, BUFFERED_ENTRY_LIMIT);
          if (kind === "image/svg+xml") assertPassiveSvg(entry.getData());
        } catch (error) {
          issues.push({
            severity: "error",
            status: "unverified",
            code: error instanceof MdkValidationError ? error.code : "E_MEDIA_PREVIEW",
            path: source,
            message: String(error) + " " + target.path,
          });
        }
      }
    }
  };
  const headings = new Map<string, Set<string>>();
  let style: Table = {};
  try {
    style = optionalTable(doc, "settings.toml");
  } catch {
    /* Reported separately. */
  }
  const fonts = new Set<string>();
  const collect = (value: unknown, depth: number) => {
    if (!isTable(value) || depth > 2) return;
    for (const [key, item] of Object.entries(value)) {
      if (
        key === "font" &&
        typeof item === "string" &&
        item.startsWith("resources/")
      )
        fonts.add(item);
      else if (key === "font_fallbacks" && Array.isArray(item)) {
        for (const font of item)
          if (typeof font === "string" && font.startsWith("resources/"))
            fonts.add(font);
      } else if (isTable(item)) collect(item, depth + 1);
    }
  };
  for (const section of [
    "body",
    "headings",
    "inline_code",
    "code",
    "quote",
    "lists",
    "tasks",
    "tables",
    "images",
  ])
    collect(style[section], 0);
  if (Array.isArray(style.font_sets))
    for (const fontSet of style.font_sets)
      if (isTable(fontSet))
        for (const key of ["regular", "bold", "italic", "bold_italic"]) {
          const font = fontSet[key];
          if (typeof font === "string" && font.startsWith("resources/"))
            fonts.add(font);
        }
  for (const font of fonts) {
    used.add(font);
    if (!files.has(font))
      issues.push({
        severity: "error",
        code: "E_RESOURCE_MISSING",
        path: "settings.toml",
        message: t("引用的字体不存在：") + font,
      });
    else {
      const kind = detectMediaType(doc.zip.getEntry(font)!.prefix());
      if (!kind?.startsWith("font/"))
        issues.push({
          severity: "error",
          status: "unverified",
          code: "E_FONT",
          path: font,
          message: t("无法验证字体格式。"),
        });
    }
  }
  for (const entry of doc.zip
    .getEntries()
    .filter(
      (e) => e.entryName.startsWith("markdown/") && e.entryName.endsWith(".md"),
    )) {
    let source: string;
    try {
      source = text(entry.getData());
    } catch (error) {
      issues.push({
        severity: "error",
        code: error instanceof MdkValidationError ? error.code : "E_TEXT_ENCODING",
        status: error instanceof MdkValidationError ? error.status : undefined,
        path: entry.entryName,
        message: String(error),
      });
      continue;
    }
    const walk = (tokens: Token[]) => {
      for (const token of tokens) {
        const url =
          token.type === "image"
            ? token.attrGet("src")
            : token.type === "link_open"
              ? token.attrGet("href")
              : null;
        if (url !== null) check(entry.entryName, url, token.type === "image");
        if (token.children) walk(token.children);
      }
    };
    if (source.includes("[") || source.includes("<"))
      walk(markdownParser.parse(source, {}));
  }
  for (const name of files)
    if (name.startsWith("resources/") && !used.has(name))
      issues.push({
        severity: "info",
        code: "W_RESOURCE_ORPHAN",
        path: name,
        message: t("未发现已知引用；作为附件保留，不自动清理。"),
      });
  return issues;
}
function diagnostics(doc: Document): ValidationIssue[] {
  const issues: ValidationIssue[] = [];
  const control = contents(doc),
    header = manifest(doc),
    view = settingsInfo(doc);
  const files = new Map(
    doc.zip
      .getEntries()
      .filter((entry) => !entry.isDirectory)
      .map((entry) => [entry.entryName, entry]),
  );
  for (const entry of control.documents ?? [])
    if (!files.has(entry.path))
      issues.push({
        scope: "content",
        severity: "error",
        code: "mdk.content.missing",
        path: entry.path,
        message: t(
          "目录指向的文稿缺失；允许保存未完成工程，交付前需恢复文件或删除条目。",
        ),
      });
  for (const field of header.required)
    issues.push({
      scope: "core",
      status: "unverified",
      severity: "error",
      code: "mdk.capability.unsupported",
      path: "mdk.toml",
      field: "features.required",
      message: t("工程需要当前应用未支持的能力：{0}", field),
    });
  for (const feature of header.optional)
    issues.push({
      scope: "presentation",
      status: "unverified",
      severity: "warning",
      code: "mdk.capability.unsupported",
      path: "mdk.toml",
      field: "features.optional",
      message: t("可选能力未完整实现，数据已保留：{0}", feature),
    });
  for (const problem of view.problems)
    issues.push({
      scope: "presentation",
      severity: "error",
      code: "mdk.settings.invalid",
      path: "settings.toml",
      ...problem,
    });
  for (const field of view.unsupported)
    issues.push({
      scope: "presentation",
      status: "unverified",
      severity: "warning",
      code: "mdk.capability.unsupported",
      path: "settings.toml",
      field,
      message: t("当前展示器未实现此设置：{0}", field),
    });
  for (const item of referenceIssues(doc)) {
    const status =
      item.status ??
      (item.code === "E_EXTERNAL_MEDIA" ? "unverified" : undefined);
    issues.push({
      ...item,
      scope: item.code === "E_MEDIA_PREVIEW" || item.code === "mdk.limit.exceeded" ? "presentation" : "content",
      status,
      code:
        item.code === "E_RESOURCE_MISSING"
          ? "mdk.content.missing"
          : item.code.startsWith("W_")
            ? "com.mardikor.resource.unreferenced"
            : item.code === "mdk.limit.exceeded" ? item.code : status === "unverified"
              ? "mdk.capability.unsupported"
              : "com.mardikor.content.invalid",
    });
  }
  if (typeof header.metadata?.cover === "string") {
    const target = files.get(header.metadata.cover);
    if (!target)
      issues.push({
        scope: "content",
        severity: "error",
        code: "mdk.content.missing",
        path: "mdk.toml",
        field: "metadata.cover",
        message: t("封面资源缺失：{0}", header.metadata.cover),
      });
    else {
      const kind = detectMediaType(target.prefix());
      if (!kind || !["image/png", "image/jpeg", "image/svg+xml"].includes(kind))
        issues.push({
          scope: "content",
          status: "unverified",
          severity: "error",
          code: "mdk.capability.unsupported",
          path: header.metadata.cover,
          message: t("封面格式无法验证。"),
        });
    }
  }
  const publishing = publicationInfo(doc);
  issues.push(
    ...publishing.issues,
    ...publishing.presets.flatMap((preset) => preset.issues),
  );
  const normalized = new Map<string, string>();
  const nonportable = new Set<string>();
  const pathDepth = (name: string) => name.split("/");
  for (const name of files.keys()) {
    const parts = pathDepth(name);
    if (
      parts.some(
        (part) =>
          /[<>"|?*]|[. ]$|^(?:con|prn|aux|nul|com[1-9¹²³]|lpt[1-9¹²³])(?:\.|$)/i.test(
            part,
          ) ||
          part.length > 255 ||
          Buffer.byteLength(part) > 255,
      )
    )
      nonportable.add(name);
    for (let depth = 1; depth <= parts.length; depth++) {
      const prefix = parts.slice(0, depth).join("/");
      const key = prefix.normalize("NFC").toLowerCase();
      if (normalized.has(key) && normalized.get(key) !== prefix)
        nonportable.add(name);
      else normalized.set(key, prefix);
    }
    const escaped = displayArchivePath(name);
    if (escaped !== name) {
      issues.push({
        scope: "portability",
        severity: "warning",
        code: "mdk.path.nonportable",
        path: escaped,
        message: t("路径含双向控制字符：{0}", escaped),
      });
    }
  }
  for (const name of nonportable)
    issues.push({
      scope: "portability",
      severity: "warning",
      code: "mdk.path.nonportable",
      path: name,
      message: t("路径在部分平台不能安全解包。"),
    });
  return issues;
}
function deliveryIssues(doc: Document) {
  return diagnostics(doc).filter(
    ({ severity, scope }) =>
      severity === "error" && (scope === "core" || scope === "content"),
  );
}
const scopes: ValidationScope[] = [
  "container",
  "core",
  "content",
  "presentation",
  "publication",
  "portability",
];
export function validationScopes(
  issues: ValidationIssue[],
  unchecked: ValidationScope[] = [],
): NonNullable<ValidationReport["scopes"]> {
  return scopes.map((scope) => {
    const local = issues.filter((item) => item.scope === scope);
    const status = local.some(
      (item) =>
        item.status === "fail" ||
        (item.severity === "error" && item.status !== "unverified"),
    )
      ? "fail"
      : unchecked.includes(scope) ||
          local.some((item) => item.status === "unverified")
        ? "unverified"
        : "pass";
    return { scope, status, issues: local };
  });
}
function validateDocument(doc: Document): ValidationReport {
  const issues = diagnostics(doc);
  return {
    valid: !issues.some(
      (issue) =>
        issue.severity === "error" &&
        ["core", "content"].includes(issue.scope ?? ""),
    ),
    mode: doc.mode,
    issues,
    scopes: validationScopes(issues),
    summary: summary(doc),
  };
}

export function validateBareMdk(bytes: Buffer): ValidationReport {
  const doc: Document = { mode: "00", zip: readArchive(bytes) };
  doc.mode = manifest(doc).mode;
  contents(doc);
  const report = validateDocument(doc);
  const coreError = report.issues.find((issue) => issue.scope === "core" && issue.severity === "error");
  if (coreError) throw new Error(coreError.message);
  return report;
}

export function validateMdk(file: string): ValidationReport {
  try {
    return validateDocument(load(file));
  } catch (error) {
    const issue: ValidationIssue =
      error instanceof MdkValidationError
        ? {
            severity: "error",
            code: error.code,
            message: error.message,
            scope: error.scope,
            status: error.status,
            path: error.path,
            field: error.field,
          }
        : {
            severity: "error",
            code: "mdk.container.invalid",
            scope: "container",
            message: String(error),
          };
    return {
      valid: false,
      issues: [issue],
      scopes: validationScopes(
        [issue],
        scopes.filter(
          (scope) =>
            scope !== issue.scope &&
            !(issue.scope === "core" && scope === "container"),
        ),
      ),
    };
  }
}
function filterDelivery(doc: Document, selection: DeliverySelection) {
  if (
    !isTable(selection) ||
    Object.keys(selection).some(
      (key) => !["includeState", "exclude"].includes(key),
    ) ||
    (selection.includeState !== undefined &&
      typeof selection.includeState !== "boolean") ||
    (selection.exclude !== undefined &&
      (!Array.isArray(selection.exclude) ||
        selection.exclude.length > 10000 ||
        selection.exclude.some((item) => typeof item !== "string")))
  )
    throw new Error(t("交付范围无效。"));
  const omitted = new Set(selection.exclude ?? []);
  const included: string[] = [],
    excluded: string[] = [],
    selectable: string[] = [],
    persistent: string[] = [];
  for (const entry of doc.zip.getEntries()) {
    const name = entry.entryName;
    if (name.startsWith("state/")) {
      if (selection.includeState) {
        if (!entry.isDirectory) included.push(name);
      } else {
        if (!entry.isDirectory) excluded.push(name);
        doc.zip.deleteFile(name);
      }
    } else if (
      !entry.isDirectory &&
      !controlFiles.includes(name) &&
      name !== CONTENTS_MARKDOWN_PATH &&
      !name.startsWith("markdown/") &&
      !name.startsWith("resources/")
    ) {
      selectable.push(name);
      if (omitted.delete(name)) {
        persistent.push(name);
        excluded.push(name);
        doc.zip.deleteFile(name);
      } else included.push(name);
    }
  }
  if (omitted.size) throw new Error(t("交付范围包含不可剔除的文件。"));
  return { included, excluded, selectable, persistent };
}
export function planMdkExport(
  file: string,
  selection: DeliverySelection = {},
): ExportPlan {
  const doc = load(file),
    meta = filterDelivery(doc, selection),
    issues = diagnostics(doc);
  return {
    revision: doc.revision!,
    report: {
      valid: !issues.some(
        (i) =>
          i.severity === "error" &&
          (i.scope === "core" || i.scope === "content"),
      ),
      mode: doc.mode,
      issues,
      scopes: validationScopes(issues),
      summary: summary(doc),
    },
    included_meta: meta.included,
    excluded_meta: meta.excluded,
    selectable: meta.selectable,
    excluded_persistent: meta.persistent,
    confirmation_required: meta.persistent.length > 0,
    preflight_report: true,
  };
}
export function exportMdk(
  file: string,
  output: string,
  confirmedRevision = "",
  selection: DeliverySelection = {},
) {
  const plan = planMdkExport(file, selection);
  if (plan.confirmation_required && !confirmedRevision)
    throw new Error(t("请先确认本次交付剔除的文件。"));
  if (confirmedRevision && confirmedRevision !== plan.revision)
    throw new Error(t("交付预检后工程已变化，请重新预检。"));
  if (!plan.report.valid)
    throw new Error(t("请先修复严格交付检查中的错误，再交付工程。"));
  if (path.resolve(file) === path.resolve(output))
    throw new Error(t("交付必须生成独立副本，请选择其他文件名。"));
  const doc = load(file);
  if (doc.revision !== plan.revision)
    throw new Error(t("交付预检后源工程已变化，请重新预检。"));
  filterDelivery(doc, selection);
  commit(output, doc, {
    overwrite: false,
    strict: true,
  });
  return summary(doc);
}
function applySnapshot(doc: Document, snapshot: SaveSnapshot) {
  if (!isTable(snapshot) || snapshot.revision !== doc.revision)
    throw new MdkRevisionError();
  assertEditable(doc);
  const texts = [
    ...(snapshot.text ? [snapshot.text] : []),
    ...(snapshot.texts ?? []),
  ];
  if (new Set(texts.map((text) => text.path)).size !== texts.length)
    throw new Error(t("同一文件不能在一次快照中重复提交。"));
  for (const { path: internalPath, content } of texts) {
    validatePath(internalPath);
    assertWritableText(doc, internalPath);
    if (
      typeof content !== "string" ||
      /[\uD800-\uDFFF]/u.test(content) ||
      !isTextData(Buffer.from(content), internalPath)
    )
      throw new Error(t("只能写入有效的 UTF-8 文本：") + internalPath);
    validateMdkText(doc, internalPath, content);
    if (doc.zip.getEntry(internalPath) && !controlFiles.includes(internalPath))
      readText(doc, internalPath);
    put(doc, internalPath, content);
  }
  if (snapshot.positions) {
    if (texts.some((text) => text.path === "contents.toml"))
      throw new Error(t("目录源码与可视化目录存在冲突，不能相互覆盖。"));
    const control = contents(doc);
    for (const update of snapshot.positions) {
      const entry = control.entries.find((e) => e.id === update.id);
      if (!entry) throw new Error(t("目录项不存在。"));
      entry.position = update.position;
    }
    control.entries.sort((a, b) => comparePosition(a.position, b.position));
    putContents(doc, control);
  }
  if (snapshot.settings) {
    if (texts.some((text) => text.path === "settings.toml"))
      throw new Error(t("设置源码与设置表单存在冲突。"));
    writeSettings(doc, snapshot.settings);
  }
}
export function saveMdkSnapshot(
  file: string,
  snapshot: SaveSnapshot,
): MdkProject {
  const doc = load(file);
  applySnapshot(doc, snapshot);
  commit(file, doc);
  return project(doc);
}

export function prepareMdkAccessSnapshot(
  bytes: Buffer,
  revision: string,
  snapshot: SaveSnapshot,
) {
  if (bytes.length > MAX_TOTAL)
    throw new Error(t("超出实现支持范围：容器超过 256 MiB。"));
  const doc: Document = { mode: "00", zip: readArchive(bytes), revision };
  doc.mode = manifest(doc).mode;
  applySnapshot(doc, snapshot);
  const changed = snapshot.text || snapshot.texts?.length || snapshot.positions || snapshot.settings;
  const metadata = changed ? undefined : project(doc);
  if (metadata) return { bytes, project: metadata };
  const output = serializeProtected(orderedMdk(doc));
  try {
    return { bytes: output, project: project(doc) };
  } catch (error) {
    output.fill(0);
    throw error;
  }
}
export function applyMdkBatch(
  file: string,
  revision: string,
  batch: {
    newEntries: {
      id?: string;
      path: string;
      position: string;
      markdown?: string;
      title?: string;
    }[];
    writes: { id: string; markdown: string }[];
    positions: EntryPositionUpdate[];
  },
) {
  const doc = load(file, revision);
  assertEditable(doc);
  const control = contents(doc);
  const paths = new Set(
    doc.zip.getEntries().map((entry) => entry.entryName.replace(/\/$/, "")),
  );
  const texts: NonNullable<SaveSnapshot["texts"]> = [];
  const writtenIds = new Set(batch.writes.map(({ id }) => id));
  for (const item of batch.newEntries) {
    validatePath(item.path);
    if (!item.path.startsWith("markdown/") || !item.path.endsWith(".md"))
      throw new Error(t("只能将 markdown/ 下的 .md 文稿加入目录。"));
    if (paths.has(item.path))
      throw new Error(t("目标路径已存在。") + " " + item.path);
    paths.add(item.path);
    const entry = withEntryTitle(
      {
        id: item.id ?? randomUUID(),
        path: item.path,
        position: item.position,
      },
      item.title,
    );
    control.entries.push(entry);
    if (item.markdown !== undefined || !writtenIds.has(entry.id))
      texts.push({
        path: entry.path,
        content:
          item.markdown ??
          `# ${item.title ?? path.posix.basename(entry.path, ".md")}\n\n`,
      });
  }
  const byId = new Map(control.entries.map((entry) => [entry.id, entry]));
  for (const { id, position } of batch.positions) {
    const entry = byId.get(id);
    if (!entry) throw new Error(t("目录项不存在：") + id);
    entry.position = position;
  }
  for (const { id, markdown } of batch.writes) {
    const entry = manuscriptById(control, id);
    if (!entry) throw new Error(t("找不到目录项：{0}", id));
    texts.push({ path: entry.path, content: markdown });
  }
  if (batch.newEntries.length || batch.positions.length) {
    control.entries.sort((a, b) => comparePosition(a.position, b.position));
    putContents(doc, control);
  }
  applySnapshot(doc, { revision, texts });
  commit(file, doc);
  return project(doc);
}
