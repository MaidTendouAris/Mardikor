function fieldValue(raw: unknown, field: string) {
  return field
    .split(".")
    .reduce<unknown>(
      (value, key) =>
        value !== null && typeof value === "object" && Object.hasOwn(value, key)
          ? (value as Table)[key]
          : undefined,
      raw,
    );
}

function settingsProblems(
  doc: Document,
  raw: Table,
  previous = optionalPreviousTable(doc, "settings.toml"),
) {
  const next = inspectV2Settings(raw, doc.mode).problems;
  if (!previous) return next;
  const before = inspectV2Settings(previous, doc.mode).problems;
  const dependencies: Record<string, string[]> = {
    "preview.geometry": [
      "preview.layout",
      "preview.max_width",
      "preview.viewport_height",
      "preview.padding_block",
      "preview.padding_inline",
      "preview.border_width",
      "body.writing_mode",
    ],
    "toc.heading_range": ["toc.heading_min_level", "toc.heading_max_level"],
  };
  return next.filter(
    ({ field, message }) =>
      !before.some(
        (issue) => issue.field === field && issue.message === message,
      ) ||
      (dependencies[field] ?? [field]).some(
        (key) =>
          !isDeepStrictEqual(fieldValue(previous, key), fieldValue(raw, key)),
      ),
  );
}

function writeSettings(doc: Document, value: MdkSettings) {
  const info = settingsInfo(doc);
  if (info.readonly) throw new Error(t("请先在源码中修复 settings.toml。"));
  const raw = doc.zip.getEntry("settings.toml")
    ? coreTable(doc, "settings.toml")
    : {};
  const next = updateV2Settings(raw, info.settings, value);
  const errors = settingsProblems(doc, next.raw, raw);
  if (errors.length)
    throw new Error(errors.map(({ message }) => message).join("\n"));
  if (next.changed) put(doc, "settings.toml", stringify(next.raw));
}
function validateMdkText(doc: Document, name: string, source: string) {
  if (name === "mdk.toml") inspectManifest(parseCoreSource(source));
  else if (name === "contents.toml") inspectOutline(parseCoreSource(source));
  else if (name === "settings.toml") {
    const problems = settingsProblems(doc, parseCoreSource(source));
    if (problems.length)
      throw new Error(problems.map(({ message }) => message).join("\n"));
  } else if (name === "publication.toml") {
    const raw = parseCoreSource(source);
    const previous = optionalPreviousTable(doc, "publication.toml");
    const authoredErrors = (value: Table) => {
      const info = inspectV2Publication(value, {}, doc.mode);
      return [
        ...info.issues,
        ...info.presets.flatMap(({ issues }) => issues),
      ].filter(({ status }) => status === "fail");
    };
    const invalid = previous ? authoredErrors(previous) : [];
    const errors = authoredErrors(raw).filter(
      ({ field, message }) =>
        !field ||
        !invalid.some(
          (issue) => issue.field === field && issue.message === message,
        ) ||
        !isDeepStrictEqual(fieldValue(previous, field), fieldValue(raw, field)),
    );
    if (errors.length)
      throw new Error(errors.map(({ message }) => message).join("\n"));
  } else validateSourceText(name, source);
}

