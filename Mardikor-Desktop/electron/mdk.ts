function rewriteMdkPaths(
  doc: Document,
  rename: (source: string) => string | undefined,
) {
  if (
    manifest(doc).optional.some((feature) => feature !== "mdk.settings-full@1")
  )
    throw new Error(t("工程含未验证扩展，无法确认改名不会破坏关联。"));
  const members = doc.zip.getEntries();
  for (const entry of members) {
    if (
      entry.isDirectory ||
      !entry.entryName.startsWith("markdown/") ||
      !entry.entryName.endsWith(".md")
    )
      continue;
    const source = text(entry.getData());
    const next = rewriteResourceLinks(
      markdownParser,
      entry.entryName,
      source,
      rename,
      rename(entry.entryName),
    );
    if (next !== source) put(doc, entry.entryName, next);
  }
  for (const filename of ["mdk.toml", "settings.toml", "publication.toml"]) {
    if (!doc.zip.getEntry(filename)) continue;
    const original = readText(doc, filename),
      table = parseCoreSource(original);
    const changes = new Map<string, string>();
    const mapping = (value: unknown) => {
      if (typeof value !== "string" || !value.startsWith("resources/"))
        return value;
      const next = rename(value);
      if (next) changes.set(value, next);
      return next ?? value;
    };
    function fontPaths(section: unknown, depth = 0) {
      if (!isTable(section) || depth > 2) return;
      for (const [key, value] of Object.entries(section)) {
        if (key === "font") section[key] = mapping(value);
        else if (key === "font_fallbacks" && Array.isArray(value))
          section[key] = value.map(mapping);
        else if (isTable(value) && /^h[1-6]$/.test(key))
          fontPaths(value, depth + 1);
      }
    }
    const updateStyle = (style: Table) => {
      for (const key of [
        "body",
        "headings",
        "inline_code",
        "code",
        "quote",
        "tables",
        "lists",
        "tasks",
        "images",
      ])
        fontPaths(style[key]);
    };
    if (
      filename === "mdk.toml" &&
      isTable(table.metadata) &&
      Object.hasOwn(table.metadata, "cover")
    )
      table.metadata.cover = mapping(table.metadata.cover);
    if (filename === "settings.toml") {
      updateStyle(table);
      if (Array.isArray(table.font_sets))
        for (const item of table.font_sets)
          if (isTable(item))
            for (const key of ["regular", "bold", "italic", "bold_italic"])
              if (Object.hasOwn(item, key)) item[key] = mapping(item[key]);
    }
    if (filename === "publication.toml" && Array.isArray(table.presets))
      for (const preset of table.presets)
        if (isTable(preset)) updateStyle(preset);
    if (!changes.size) continue;
    const updated = original.replace(
      /"(?:\\[^\r\n]|[^"\\\r\n])*"|'[^'\r\n]*'/g,
      (literal) => {
        let value: unknown;
        try {
          value = parseToml("value = " + literal).value;
        } catch {
          return literal;
        }
        if (typeof value !== "string") return literal;
        const next = changes.get(value);
        return next ? JSON.stringify(next) : literal;
      },
    );
    // Keep original layout when a textual edit changes exactly the known values.
    let matched = false;
    try {
      matched = isDeepStrictEqual(parseCoreSource(updated), table);
    } catch {
      /* Reserialize the changed table. */
    }
    put(doc, filename, matched ? updated : stringify(table));
  }
  const changed = members.flatMap((member) => {
    const next = rename(member.entryName);
    return next ? [{ member, next }] : [];
  });
  for (const { member } of changed) {
    if (
      [bundledFontPath, "resources/other/Mardikor-Noto-OFL.txt"].includes(
        member.entryName,
      )
    )
      throw new Error(t("内置字体及其许可证由 Mardikor 管理。"));
  }
  for (const { member, next } of changed)
    doc.zip.set(member.renamed(next));
  for (const { member } of changed) doc.zip.deleteFile(member.entryName);
}
