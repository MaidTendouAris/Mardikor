import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const source = "https://www.unicode.org/Public/15.1.0/ucd/UnicodeData.txt";
const expected =
  "2fc713e6a31a87c4850a37fe2caffa4218180fadb5de86b43a143ddb4581fb86";
if (!process.argv[2])
  throw new Error("Pass the path to UnicodeData.txt from " + source);
const bytes = readFileSync(process.argv[2]);
if (createHash("sha256").update(bytes).digest("hex") !== expected)
  throw new Error("Expected the Unicode 15.1.0 table from " + source);

const assigned = [];
const lettersMarksNumbers = [];
function add(ranges, first, last) {
  const previous = ranges.at(-1);
  if (previous && previous[1] + 1 === first) previous[1] = last;
  else ranges.push([first, last]);
}
let begin;
for (const record of bytes.toString("utf8").split("\n").filter(Boolean)) {
  const [hex, name, category] = record.split(";");
  const point = Number.parseInt(hex, 16);
  if (name.endsWith(", First>")) {
    begin = point;
    continue;
  }
  const start = begin ?? point;
  begin = undefined;
  add(assigned, start, point);
  if (/^[LMN]/.test(category)) add(lettersMarksNumbers, start, point);
}
function pattern(name, ranges, before, after) {
  const escape = (point) => "\\\\u{" + point.toString(16) + "}";
  const fragments = ranges.map(([first, last]) =>
    first === last ? escape(first) : escape(first) + "-" + escape(last),
  );
  const lines = [];
  for (let offset = 0; offset < fragments.length; offset += 6)
    lines.push('  "' + fragments.slice(offset, offset + 6).join("") + '" +');
  return [
    "export const " + name + " = new RegExp(",
    '  "' + before + '" +',
    ...lines,
    '  "' + after + '", "gu",',
    ");",
  ].join("\n");
}
const output = [
  "// Generated by scripts/generate-mdk-unicode.mjs from " + source,
  "// Unicode Data Files and Software License: assets/unicode-license.txt.",
  pattern("assignedUnicode151", assigned, "[", "]+"),
  pattern("outsideHeadingUnicode151", lettersMarksNumbers, "[^", "_-]"),
  "",
].join("\n");
writeFileSync(new URL("../shared/unicode-15-1.ts", import.meta.url), output);
